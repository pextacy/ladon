// Measures the two PRD latency targets (docs/PRD.md §4) and writes docs/BENCH.md:
//   1. cached verdict < 300 ms   — checkPackage on a warm cache, median + p95 over several packages
//   2. gate → Key → approve < 10 s — full CLI gate on a held install, approved by a simulated Ladon Key
//      that speaks the real USB protocol (DOCS §6) and holds the button for the firmware's 1.5 s.
// Needs network for the public registries. Run: pnpm bench
import { generateKeyPairSync, sign } from "node:crypto";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

// The CLI reads LADON_HOME at import time: point it at a throwaway home first.
const home = mkdtempSync(join(tmpdir(), "ladon-bench-"));
process.env.LADON_HOME = home;

const core = await import("../packages/core/dist/index.js");
const { gate } = await import("../packages/cli/dist/gate.js");
const { KeyBridge } = await import("../packages/cli/dist/approve/key.js");

const HOLD_MS = 1500; // firmware HOLD_TO_APPROVE_MS
const ms = (t0) => Number(process.hrtime.bigint() - t0) / 1e6;
const median = (xs) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)];
const p95 = (xs) => [...xs].sort((a, b) => a - b)[Math.min(xs.length - 1, Math.ceil(xs.length * 0.95) - 1)];

// ---------- 1. cached verdict ----------
const deps = core.createDeps({ cacheDir: join(home, "cache"), atlasUrl: process.env.LADON_ATLAS_URL ?? "" });
const pkgs = [["npm", "react"], ["npm", "express"], ["npm", "lodash"], ["npm", "esbuild"], ["npm", "left-pad"], ["pypi", "requests"], ["pypi", "numpy"], ["pypi", "flask"]];
const cold = [];
const warm = [];
for (const [ecosystem, name] of pkgs) {
  let t0 = process.hrtime.bigint();
  const first = await core.checkPackage({ ecosystem, name }, deps);
  cold.push(ms(t0));
  if (first.evidence.errors.some((e) => e.critical)) console.warn(`  ! ${ecosystem}:${name}: ${first.evidence.errors.map((e) => e.message).join("; ")}`);
  for (let i = 0; i < 5; i++) {
    // fresh sources over the same on-disk cache: what a newly started daemon/CLI sees
    const fresh = core.createDeps({ cacheDir: join(home, "cache"), atlasUrl: process.env.LADON_ATLAS_URL ?? "" });
    t0 = process.hrtime.bigint();
    await core.checkPackage({ ecosystem, name }, fresh);
    warm.push(ms(t0));
  }
}
console.log(`cached verdict: median ${median(warm).toFixed(1)} ms, p95 ${p95(warm).toFixed(1)} ms (uncached median ${median(cold).toFixed(0)} ms)`);

// ---------- 2. gate → Key → approve ----------
const { publicKey, privateKey } = generateKeyPairSync("ed25519");
const pkHex = publicKey.export({ format: "der", type: "spki" }).subarray(-32).toString("hex");
writeFileSync(join(home, "config.json"), JSON.stringify({ webUrl: "http://127.0.0.1:9/", dashboard: false, key: { publicKey: pkHex, pairedAt: new Date().toISOString() } }));

// monotonic counter persisted across connections, like the firmware's NVS counter
let ctr = 0;

/** In-memory serial link that behaves like firmware/src/main.cpp: hello, time, req → hold 1.5 s → signed res. */
function simulatedKey() {
  const listeners = new Set();
  const emit = (o) => setImmediate(() => listeners.forEach((l) => l(JSON.stringify(o))));
  return {
    path: "sim://ladon-key",
    async write(line) {
      const m = JSON.parse(line);
      if (m.t === "hello") emit({ t: "hello", v: 1, pk: pkHex, ctr, name: "sim" });
      if (m.t === "req") {
        setTimeout(() => {
          ctr++;
          const sig = sign(null, Buffer.from(core.keySignedMessage(m, true, ctr)), privateKey).toString("hex");
          emit({ t: "res", id: m.id, ok: true, ctr, sig });
        }, HOLD_MS);
      }
    },
    onLine(cb) {
      listeners.add(cb);
      return () => listeners.delete(cb);
    },
    async close() {},
  };
}

const loops = [];
for (let i = 0; i < 3; i++) {
  const name = `ladon-bench-not-a-real-package-${Date.now().toString(36)}-${i}`;
  const bridge = new KeyBridge(async () => simulatedKey());
  const t0 = process.hrtime.bigint();
  const r = await gate({ command: `npm install ${name}`, cwd: home, agent: "bench" }, { approvers: [bridge] });
  const t = ms(t0);
  if (r.verdict !== "hold" || r.outcome !== "approved") throw new Error(`unexpected gate result: verdict=${r.verdict} outcome=${r.outcome} ${r.approval?.detail ?? ""}`);
  loops.push(t);
}
console.log(`gate → Key → approve: median ${(median(loops) / 1000).toFixed(2)} s (includes the ${HOLD_MS / 1000} s physical hold)`);

const ok1 = median(warm) < 300;
const ok2 = median(loops) < 10_000;
const md = `# Latency benchmark

Generated by \`pnpm bench\` (\`scripts/bench.mjs\`) on ${new Date().toISOString().slice(0, 10)}, Node ${process.version}.
Targets from \`docs/PRD.md\` §4.

| Metric | Target | Result | |
|---|---|---|---|
| Cached verdict (median of ${warm.length}, ${pkgs.length} packages × 5, fresh process-level sources over the on-disk cache) | < 300 ms | **${median(warm).toFixed(1)} ms** (p95 ${p95(warm).toFixed(1)} ms) | ${ok1 ? "✓ met" : "✗ missed"} |
| Uncached verdict (median, live registries) | < 2.5 s | ${median(cold).toFixed(0)} ms | ${median(cold) < 2500 ? "✓ met" : "✗ missed"} |
| gate → Key → approve loop (median of ${loops.length}) | < 10 s | **${(median(loops) / 1000).toFixed(2)} s** | ${ok2 ? "✓ met" : "✗ missed"} |

The loop runs the real CLI gate (\`packages/cli/src/gate.ts\`) on a held install (a package name that
does not exist → R01), through the real Key bridge and signature verification
(\`packages/cli/src/approve/key.ts\`), against a simulated Key that speaks the USB protocol from
\`docs/DOCS.md\` §6 and waits the firmware's 1.5 s hold before signing with its own Ed25519 key.
`;
writeFileSync(new URL("../docs/BENCH.md", import.meta.url), md);
console.log(ok1 && ok2 ? "both targets met → docs/BENCH.md" : "TARGET MISSED → docs/BENCH.md");
process.exit(ok1 && ok2 ? 0 : 1);
