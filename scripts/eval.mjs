// Runs the Judge on fixtures/corpus.json and writes docs/EVAL.md (confusion matrix) + fixtures/eval-results.json.
// Needs network (public registries) and the local Verdaccio with canaries (pnpm demo:registry && pnpm demo:publish-canaries).
import { readFileSync, writeFileSync } from "node:fs";
import { checkPackage, countedHits, createDeps } from "../packages/core/dist/index.js";

const corpus = JSON.parse(readFileSync(new URL("../fixtures/corpus.json", import.meta.url), "utf8"));
const pub = createDeps({ atlasUrl: process.env.LADON_ATLAS_URL ?? "" });
const local = createDeps({ npmRegistry: process.env.LADON_DEMO_REGISTRY ?? "http://localhost:4873/", atlasUrl: "" });

const rows = [];
for (const [cls, list] of Object.entries({ benign: corpus.benign, malicious: corpus.malicious, hallucinated: corpus.hallucinated })) {
  for (const [ecosystem, name] of list) {
    const deps = cls === "malicious" ? local : pub;
    const r = await checkPackage({ ecosystem, name }, deps);
    rows.push({ cls, ecosystem, name, version: r.version ?? null, verdict: r.verdict, score: r.score, rules: countedHits(r.hits).map((h) => h.id), errors: r.evidence.errors.map((e) => e.source), ms: r.durationMs });
    process.stdout.write(`${r.verdict.padEnd(5)} ${String(r.score).padStart(3)}  ${cls.padEnd(12)} ${ecosystem}:${name}  ${countedHits(r.hits).map((h) => h.id).join(",")}\n`);
  }
}

const count = (cls, v) => rows.filter((r) => r.cls === cls && r.verdict === v).length;
const total = (cls) => rows.filter((r) => r.cls === cls).length;
const bad = ["malicious", "hallucinated"];
const badHeld = bad.reduce((s, c) => s + count(c, "hold"), 0);
const badTotal = bad.reduce((s, c) => s + total(c), 0);
const benignHeld = count("benign", "hold");
const pct = (a, b) => `${((100 * a) / Math.max(1, b)).toFixed(1)} %`;
const misses = rows.filter((r) => (bad.includes(r.cls) && r.verdict !== "hold") || (r.cls === "benign" && r.verdict !== "allow"));

const md = `# Evaluation — Judge on the fixture corpus

Generated by \`pnpm eval\` on ${new Date().toISOString().slice(0, 10)} (core ${JSON.parse(readFileSync(new URL("../packages/core/package.json", import.meta.url), "utf8")).version}, \`LADON_AI=off\` — deterministic rules only).

Corpus (\`fixtures/corpus.json\`): ${total("benign")} benign real packages (npm + PyPI), ${total("malicious")} harmless
canary packages on the local Verdaccio that imitate real attack shapes, ${total("hallucinated")} non-existent / hallucination-shaped names.

## Confusion matrix

| actual \\ verdict | ✓ allow | ▲ warn | ■ hold |
|---|---:|---:|---:|
| benign | ${count("benign", "allow")} | ${count("benign", "warn")} | ${count("benign", "hold")} |
| malicious (canary) | ${count("malicious", "allow")} | ${count("malicious", "warn")} | ${count("malicious", "hold")} |
| hallucinated | ${count("hallucinated", "allow")} | ${count("hallucinated", "warn")} | ${count("hallucinated", "hold")} |

- **Bad caught (held): ${badHeld}/${badTotal} = ${pct(badHeld, badTotal)}** (target ≥ 90 %)
- **Benign held: ${benignHeld}/${total("benign")} = ${pct(benignHeld, total("benign"))}** (target ≤ 5 %)
- Median verdict time: ${rows.map((r) => r.ms).sort((a, b) => a - b)[Math.floor(rows.length / 2)]} ms (uncached)

## Not perfect

${misses.length === 0 ? "No misses on this corpus." : misses.map((r) => `- \`${r.ecosystem}:${r.name}\` (${r.cls}) → ${r.verdict} ${r.score} — rules: ${r.rules.join(", ") || "none"}`).join("\n")}

Caveats: the malicious set is our own canaries, so it measures whether the rules catch known *shapes*, not
novel attacks. Names in the hallucinated set are synthetic unless they come from the Atlas seed.

## All results

| class | package | version | verdict | score | rules |
|---|---|---|---|---:|---|
${rows.map((r) => `| ${r.cls} | ${r.ecosystem}:${r.name} | ${r.version ?? "—"} | ${r.verdict} | ${r.score} | ${r.rules.join(", ")} |`).join("\n")}
`;
writeFileSync(new URL("../docs/EVAL.md", import.meta.url), md);
writeFileSync(new URL("../fixtures/eval-results.json", import.meta.url), JSON.stringify({ date: new Date().toISOString(), rows }, null, 2) + "\n");
console.log(`\nbad caught ${pct(badHeld, badTotal)}, benign held ${pct(benignHeld, total("benign"))} → docs/EVAL.md`);
